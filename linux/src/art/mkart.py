#!/usr/bin/env python3
"""
Package the live-USB GRUB theme. The pictures themselves are drawn by mktheme (C, using the
SilverOS renderer); this script only converts them to PNG, cuts the menu-item boxes, and
writes theme.txt. No image libraries: a minimal PNG encoder is included.

    mkart.py <raw dir from mktheme> <theme outdir>
"""
import math, os, struct, sys, zlib

INK = (14, 14, 16)

def png(path, w, h, rgba):
    raw = b''.join(b'\x00' + rgba[y * w * 4:(y + 1) * w * 4] for y in range(h))
    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))

def opaque(raw):                       # BGRX -> RGBA
    out = bytearray(len(raw))
    out[0::4] = raw[2::4]; out[1::4] = raw[1::4]; out[2::4] = raw[0::4]; out[3::4] = b'\xff' * (len(raw) // 4)
    return bytes(out)

def ink_on_clear(raw):                 # dark-on-white drawing -> ink with darkness as alpha
    n = len(raw) // 4
    out = bytearray(len(raw))
    out[0::4] = bytes([INK[0]]) * n; out[1::4] = bytes([INK[1]]) * n; out[2::4] = bytes([INK[2]]) * n
    out[3::4] = bytes(255 - g for g in raw[1::4])
    return bytes(out)

def rounded_box(outdir, prefix, border, border_a, fill, fill_a, stroke, B=16):
    """A rounded box cut into 9 pieces; GRUB stretches it around each menu item."""
    S, n = 4, 3 * B
    px = bytearray(n * n * 4)
    r = B - 2
    for y in range(n):
        for x in range(n):
            fa = ba = 0
            for j in range(S):
                for i in range(S):
                    fx, fy = x + (i + .5) / S, y + (j + .5) / S
                    dx = max(1 + r - fx, 0, fx - (n - 1 - r)); dy = max(1 + r - fy, 0, fy - (n - 1 - r))
                    d = math.hypot(dx, dy) if (dx or dy) else -min(fx - 1, n - 1 - fx, fy - 1, n - 1 - fy) + r
                    if d <= r:
                        fa += 1
                        if d >= r - stroke: ba += 1
            fa /= S * S; ba /= S * S
            a = ba * border_a + (fa - ba) * fill_a
            if a > 0:
                col = [(border[k] * ba * border_a + fill[k] * (fa - ba) * fill_a) / a for k in range(3)]
                px[(y * n + x) * 4:(y * n + x) * 4 + 4] = bytes([round(col[0]), round(col[1]), round(col[2]), round(a * 255)])
    for name, (gx, gy) in {'nw': (0, 0), 'n': (1, 0), 'ne': (2, 0), 'w': (0, 1), 'c': (1, 1), 'e': (2, 1), 'sw': (0, 2), 's': (1, 2), 'se': (2, 2)}.items():
        piece = b''.join(bytes(px[((gy * B + y) * n + gx * B) * 4:((gy * B + y) * n + gx * B + B) * 4]) for y in range(B))
        png(os.path.join(outdir, f'{prefix}_{name}.png'), B, B, piece)

THEME = """# SilverOS live-USB boot menu -- generated by src/art/mkart.py
title-text: ""
desktop-image: "background.png"
desktop-image-scale-method: "stretch"
desktop-color: "#eeeff2"
message-color: "#0e0e10"
message-bg-color: "#eeeff2"

+ boot_menu {
    left = 50%-350
    top = 50%-128
    width = 700
    height = 380
    item_height = 140
    item_spacing = 44
    item_padding = 10
    icon_width = 600
    icon_height = 128
    item_icon_space = 0
    item_color = "#eeeff2"
    selected_item_color = "#eeeff2"
    item_pixmap_style = "item_*.png"
    selected_item_pixmap_style = "select_*.png"
    scrollbar = false
}

+ progress_bar {
    id = "__timeout__"
    left = 50%-200
    top = 50%+262
    width = 400
    height = 5
    show_text = false
    fg_color = "#0e0e10"
    bg_color = "#c9cbd2"
    border_color = "#c9cbd2"
}
"""

def main():
    raw, out = sys.argv[1:3]
    os.makedirs(os.path.join(out, 'icons'), exist_ok=True)
    png(os.path.join(out, 'background.png'), 1280, 720, opaque(open(os.path.join(raw, 'background.raw'), 'rb').read()))
    for n in ('silveros', 'windows', 'advanced'):
        png(os.path.join(out, 'icons', n + '.png'), 600, 128, ink_on_clear(open(os.path.join(raw, f'tile_{n}.raw'), 'rb').read()))
    rounded_box(out, 'item', (120, 124, 134), 0.45, (255, 255, 255), 0.55, 1.5)
    rounded_box(out, 'select', INK, 1.0, (255, 255, 255), 0.96, 3)
    with open(os.path.join(out, 'theme.txt'), 'w') as f:
        f.write(THEME)

if __name__ == '__main__':
    main()
